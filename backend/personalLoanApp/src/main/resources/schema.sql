-- schema.sql: drops and recreates the tables for Customer, LoanOfficer and LoanApplication.

-- Drop in reverse dependency order (loan_application references the other two)
DROP TABLE IF EXISTS loan_application CASCADE;
DROP TABLE IF EXISTS loan_officer CASCADE;
DROP TABLE IF EXISTS customer CASCADE;
DROP SEQUENCE IF EXISTS loan_application_seq;

-- Customer.java
CREATE TABLE customer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    CONSTRAINT uk_customer_username UNIQUE (username)
);

-- LoanOfficer.java
CREATE TABLE loan_officer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    CONSTRAINT uk_loan_officer_username UNIQUE (username)
);

-- LoanApplication.java (ids start at 1001 -> references LN-1001, LN-1002, ...)
CREATE SEQUENCE loan_application_seq START WITH 1001 INCREMENT BY 1;

CREATE TABLE loan_application (
    id                    BIGINT PRIMARY KEY DEFAULT nextval('loan_application_seq'),
    customer_id           BIGINT        NOT NULL,
    request_key           UUID          NOT NULL,
    loan_amount           NUMERIC(12,2) NOT NULL,
    term_months           INTEGER       NOT NULL,
    purpose               VARCHAR(200)  NOT NULL,
    employment_status     VARCHAR(20)   NOT NULL,
    monthly_income        NUMERIC(12,2) NOT NULL,
    status                VARCHAR(20)   NOT NULL,
    submitted_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    decision_note         VARCHAR(1000),
    decided_at            TIMESTAMP(6) WITH TIME ZONE,
    decided_by_officer_id BIGINT,
    CONSTRAINT fk_loan_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT fk_loan_decided_by_officer FOREIGN KEY (decided_by_officer_id) REFERENCES loan_officer (id),
    CONSTRAINT uk_loan_customer_request_key UNIQUE (customer_id, request_key),
    -- Pending rows have no decision fields; decided rows have all of them, and a rejection has a reason
    CONSTRAINT ck_loan_decision_consistent CHECK (
        (status = 'SUBMITTED' AND decided_at IS NULL
            AND decided_by_officer_id IS NULL AND decision_note IS NULL)
        OR (status IN ('APPROVED', 'REJECTED') AND decided_at IS NOT NULL
            AND decided_by_officer_id IS NOT NULL
            AND (status <> 'REJECTED' OR NULLIF(BTRIM(decision_note), '') IS NOT NULL))
    )
);

-- Customer history index
-- Supports customer-specific loan history ordered newest first.
CREATE INDEX idx_loan_application_customer_history
ON loan_application (
    customer_id,
    submitted_at DESC,
    id DESC
);

-- Officer pending queue index
-- Only indexes applications waiting for a decision.
CREATE INDEX idx_loan_application_pending_queue
ON loan_application (
    submitted_at ASC,
    id ASC
)
WHERE status = 'SUBMITTED';
